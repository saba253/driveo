"use client";

import { useActionState, useState, useTransition } from "react";
import {
  startEnrollmentAction,
  verifyChallengeAction,
  verifyEnrollmentAction,
  type EnrollmentState,
  type FormState,
} from "@/app/admin/actions";
import { Button } from "@/components/ui/Button";
import { Field, Input } from "@/components/ui/Field";
import { ka } from "@/content/ka";
import { FormMessage } from "./AdminCard";

const t = ka.admin.mfa;

function CodeField() {
  return (
    <Field label={t.code} htmlFor="admin-totp">
      <Input
        id="admin-totp"
        name="code"
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="[0-9 ]*"
        maxLength={7}
        required
        className="tracking-[0.3em]"
      />
    </Field>
  );
}

export function MfaChallengeForm() {
  const [state, action, pending] = useActionState<FormState, FormData>(verifyChallengeAction, { error: null });
  return (
    <form action={action} className="grid gap-5" noValidate>
      <FormMessage>{state.error}</FormMessage>
      <CodeField />
      <Button type="submit" size="lg" disabled={pending}>
        {pending ? t.pending : t.verify}
      </Button>
    </form>
  );
}

export function MfaEnrollForm() {
  const [enrollment, setEnrollment] = useState<EnrollmentState | null>(null);
  const [starting, startTransition] = useTransition();
  const [state, action, pending] = useActionState<EnrollmentState, FormData>(verifyEnrollmentAction, { error: null });

  if (!enrollment?.factorId) {
    return (
      <div className="grid gap-5">
        <FormMessage>{enrollment?.error}</FormMessage>
        <Button size="lg" disabled={starting} onClick={() => startTransition(async () => setEnrollment(await startEnrollmentAction()))}>
          {starting ? t.pending : t.enrollStart}
        </Button>
      </div>
    );
  }

  return (
    <form action={action} className="grid gap-5" noValidate>
      <p className="text-sm leading-relaxed text-fg-muted">{t.enrollScan}</p>
      {/* qr_code is an SVG data URI generated by Supabase Auth. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enrollment.qrCode} alt="" width={192} height={192} className="mx-auto rounded-md bg-white p-3" />
      <div>
        <p className="text-xs font-medium text-fg-subtle">{t.secretLabel}</p>
        <code className="mt-1 block break-all rounded-md bg-field px-3 py-2 font-mono text-sm text-fg select-all">{enrollment.secret}</code>
      </div>
      <input type="hidden" name="factorId" value={enrollment.factorId} />
      <FormMessage>{state.error}</FormMessage>
      <CodeField />
      <Button type="submit" size="lg" disabled={pending}>
        {pending ? t.pending : t.verify}
      </Button>
    </form>
  );
}
